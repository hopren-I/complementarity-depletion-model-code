"""Reproduce both panels of current Figure 1 from recalculated data.

Run: python code/plot_numerical_bounds.py
Requires Matplotlib and Pillow. Use --output-dir to generate a separate preview,
or --language en/zh to render one language. Does not edit or compile manuscripts.

Panel (b) reads the bundled data/validation/convergence.csv. Every saved point defines the lines;
markevery alternates visible markers only. Colors, styles and label positions
are in STYLES. Panel (a) is regenerated by bounds_panel.py from the two numerical experiments.
"""
from pathlib import Path
import csv
import io
import argparse
import hashlib
import json
import os
import tempfile

P = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--output-dir", type=Path, default=P / ".work/figures")
parser.add_argument("--language", choices=("en", "zh", "both"), default="both")
args = parser.parse_args()
ROOT = P
OUT = args.output_dir.resolve()
OUT.mkdir(parents=True, exist_ok=True)
SOURCE = P / "data/validation/convergence.csv"
os.environ.setdefault("MPLCONFIGDIR", str(P / ".work/mpl"))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib import font_manager
from matplotlib.ticker import FixedLocator, NullFormatter
from PIL import Image
from bounds_panel import render_panel_a

font_manager.fontManager.addfont(str(P / "assets/fonts/FandolHei-Regular.otf"))
with SOURCE.open() as f:
    rows = list(csv.DictReader(f))

# Solid/open circles below B=0.5; dashed/filled triangles above B=0.5.
# Each pair has contrasting colors so the solid line is visible in dash gaps.
STYLES = [
    (.49,  "#24678D", "-",          "o", [0, 2, 4, 6], 1.30),
    (.499, "#CE8B2A", "-",          "o", [0, 2, 4, 6], 13.2),
    (.501, "#28794F", (0, (4, 3)),  "^", [1, 3, 5],     4.7),
    (.51,  "#B75B42", (0, (4, 3)),  "^", [1, 3, 5],      .46),
]
series = {}
for b, *_ in STYLES:
    subset = sorted((r for r in rows if float(r["b"]) == b), key=lambda r: int(r["n"]))
    x = [int(r["n"]) for r in subset]
    y = [100*float(r["relative_halfwidth"]) for r in subset]
    assert x == [64, 128, 256, 512, 1024, 2048, 4096]
    assert all(value > 0 for value in y)
    series[b] = (x, y)

for language in (("zh", "en") if args.language == "both" else (args.language,)):
    zh = language == "zh"
    plt.rcdefaults()
    plt.rcParams.update({
        "font.size": 9, "text.color": "black", "axes.labelcolor": "black",
        "xtick.color": "black", "ytick.color": "black", "axes.titlecolor": "black",
        "axes.spines.top": False, "axes.spines.right": False,
        "axes.unicode_minus": False, "svg.fonttype": "path",
        "svg.hashsalt": "figure5b-alternating-markers-preview",
    })
    if zh:
        plt.rcParams["font.family"] = ["FandolHei", "DejaVu Sans"]

    # Match the approved panel geometry; both panels are regenerated from CSVs.
    fig = plt.figure(figsize=(3.6, 3.25), dpi=240, facecolor="white")
    ax = fig.add_axes([.143, .140, .845, .779])
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlim(52, 16000)
    ax.set_ylim(.29, 700)
    lines = []
    for b, color, linestyle, marker, markevery, label_y in STYLES:
        x, y = series[b]
        line, = ax.plot(x, y, color=color, linestyle=linestyle, linewidth=1.45,
                        marker=marker, markersize=4.1, markeredgewidth=.95,
                        markerfacecolor="white" if marker == "o" else color,
                        markevery=markevery, label=f"$B={b}$", zorder=3)
        lines.append(line)
        # Both endpoint labels lead back to the actual, unshifted coordinates.
        ax.annotate(f"$B={b}$\n{y[-1]:.3f}%", xy=(x[-1], y[-1]),
                    xytext=(5500, label_y), ha="left", va="center",
                    fontsize=7.1, color=color, linespacing=1.35,
                    arrowprops=dict(arrowstyle="-", color=color, linewidth=.65,
                                    shrinkA=2, shrinkB=2), zorder=6)

    ax.set_title("(b) 四个位置" if zh else "(b) Four locations", pad=6)
    ax.set_xlabel("单元数" if zh else "Elements", labelpad=5)
    ax.set_ylabel("相对半宽（%）" if zh else "Relative half-width (%)", labelpad=5)
    ax.xaxis.set_major_locator(FixedLocator([100, 1000]))
    # Leave room on the right for the labels; no data are added in that space.
    ax.xaxis.set_minor_formatter(NullFormatter())
    ax.yaxis.set_major_locator(FixedLocator([1, 10, 100]))
    ax.grid(which="major", alpha=.2)
    ax.legend(handles=lines, fontsize=6.6, loc="upper right", frameon=True,
              labelcolor="black", handlelength=2.6, borderpad=.5)

    if not zh:
        assert not any("\u4e00" <= c <= "\u9fff"
                       for text in fig.findobj(matplotlib.text.Text)
                       for c in text.get_text())
    buffer = io.BytesIO()
    fig.savefig(buffer, format="png", dpi=240)
    fig.savefig(OUT / f"fig_numerical_bounds_panel_b_{language}.svg", metadata={"Date": None})
    plt.close(fig)
    buffer.seek(0)
    panel = Image.open(buffer).convert("RGBA")
    original_a = render_panel_a(language)
    assert original_a.size == panel.size == (864, 780)
    combined = Image.new("RGBA", (1728, 780), "white")
    combined.paste(original_a, (0, 0))
    combined.paste(panel, (864, 0))
    assert combined.crop((0, 0, 864, 780)).tobytes() == original_a.tobytes()
    combined.save(OUT / f"fig_numerical_bounds_r2_{language}.png", dpi=(240, 240))

(OUT / "merged_bounds_plot_data.json").write_text(json.dumps({
    "source": str(SOURCE.relative_to(ROOT)),
    "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
    "data_transform": "100 * relative_halfwidth, exactly as in the current Figure 1",
    "marker_note": "All 7 points define each line; only visible marker indices alternate.",
    "panel_a": "Regenerated from bounds_baseline.csv and convergence.csv by code/bounds_panel.py",
    "series": {str(b): {"elements": x, "relative_halfwidth_percent": y}
               for b, (x, y) in series.items()},
}, ensure_ascii=False, indent=2) + "\n")
print(f"Figure 1 outputs saved to {OUT}")
