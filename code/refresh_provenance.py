"""Write current output hashes after computation, never change reference results."""
from pathlib import Path
import argparse,hashlib,json
import numpy as np
P=Path(__file__).resolve().parents[1]
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def save(path,value):
    (P/path).write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n')
def primary():
    pointer={'version':'final-portable','data_directory':'data'}
    pointer['series']=json.loads((P/'data/manifest.json').read_text())['series']
    for key,rel in [('extraction_manifest','data/manifest.json'),('results_json','data/results/posteriors.json'),('draws_npz','data/results/posterior_draws.npz'),('summary_csv','data/results/table3_summary.csv')]:
        pointer[key]=rel;pointer[key+'_sha256']=sha(P/rel)
    save('data/CURRENT_TABLE3.json',pointer)
    beta=np.load(P/'data/results/post_Si_beta.npy');v=-beta[:,0]/beta[:,1];n=-2/(1.602176634e-19*11.7*8.854187817e-14*beta[:,1])
    raw=np.genfromtxt(P/'data/si_ms_inset_digitized.csv',delimiter=',',names=True);count=int(np.sum(raw['V_app_V']<=-1))
    save('data/results/figure1_summary.json',{'posterior_source':'data/results/post_Si_beta.npy','posterior_source_sha256':sha(P/'data/results/post_Si_beta.npy'),'draw_count':len(beta),'n_fit':count,'degrees_of_freedom':count-2,'Vbi_V':[float(np.median(v)),*map(float,np.quantile(v,[.025,.975]))],'N_cm3':[float(np.median(n)),*map(float,np.quantile(n,[.025,.975]))]})
def completed():
    names=['bounds_baseline.csv','convergence.csv','bayes_repetitions.csv','stress_repetitions.csv','posterior_medians.csv','window_medians.csv','film_points.csv','sensitivity.csv']
    save('data/validation/source_manifest.json',{'scope':'regenerated by code/run_validation.py','files':{'data/validation/'+name:{'sha256':sha(P/'data/validation'/name)} for name in names}})
    files=[p for p in (P/'data').glob('insb_*.csv*')]
    save('data/insb_artifact_manifest.json',{'source_zip_sha256':sha(P/'data/insb_source_data.zip'),'sha256':{str(p.relative_to(P)):sha(p) for p in files},'scope':'current computed outputs; reference_results provides independent frozen comparison'})
if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('stage',choices=['primary','completed']);args=ap.parse_args()
    (primary if args.stage=='primary' else completed)()
